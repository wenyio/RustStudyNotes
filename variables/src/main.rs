fn main() {
    /*
    在变量名前加上 mut 使其变为可变。
    添加 mut 也能向未来阅读代码的人传达一种意图：这个变量的值将会被代码的其他部分改变。

    不能对常量使用 mut。常量不只是默认不可变，它们永远都是不可变的。声明常量时要用 const 关键字，而不是 let，并且 必须 标注值的类型。
    常量可以在任何作用域中声明，包括全局作用域，这在一个值需要被很多部分的代码用到时很有用。
    常量只能被设置为常量表达式，而不能是那些只能在运行时计算出来的值。
     */
    let mut x = 5;
    println!("The value of x is: {x}");
    x = 6;
    println!("The value of x is: {x}");

    /*
    遮蔽和把变量标记为 mut 是不同的。
    如果你不小心尝试在没有使用 let 关键字的情况下重新给变量赋值，就会得到编译时错误。
    而通过再次使用 let，我们可以对这个值做一些变换，同时又能让变量在变换完成后继续保持不可变。

    mut 和遮蔽之间的另一个区别是：当我们再次使用 let 时，实际上是在创建一个新变量，因此我们可以改变值的类型，同时继续复用相同的名字。
    例如，假设程序要求用户输入若干空格，以表示他们希望在某段文本之间显示多少空格，随后我们想把这个输入保存成一个数字：
    let spaces = "   ";
    let spaces = spaces.len();
     */
    let x = 5;

    let x = x + 1;

    {
        let x = x * 2;
        println!("The value of x in the inner scope is: {x}");
    }

    println!("The value of x is: {x}");
}
